/**
  * @brief This function handles Pendable request for system service.
  */
void PendSV_Handler(void)
{
  /* USER CODE BEGIN PendSV_IRQn 0 */

  /* USER CODE END PendSV_IRQn 0 */
  /* USER CODE BEGIN PendSV_IRQn 1 */
  __asm volatile (
    "MRS R0, PSP\n\t"

    /* Was the outgoing task using the FPU? Test EXC_RETURN bit 4. */
    "TST LR, #0x10\n\t"
    "IT EQ\n\t"
    "VSTMDBEQ R0!, {S16-S31}\n\t"

    /* Save core registers AND this task's own EXC_RETURN */
    "STMDB R0!, {R4-R11, LR}\n\t"

    "LDR R1, =TaskControlBlock_List\n\t"
    "LDR R2, =current_task_id\n\t"
    "LDRB R3, [R2]\n\t"
    "LSLS R4, R3, #2\n\t"
    "STR R0, [R1, R4]\n\t"

    "LDR R5, =task_count\n\t"
    "LDRB R5, [R5]\n\t"
    "ADD R3, R3, #1\n\t"
    "CMP R3, R5\n\t"
    "BNE 1f\n\t"
    "MOVS R3, #0\n\t"
    "1:\n\t"
    "STRB R3, [R2]\n\t"
    "LSLS R4, R3, #2\n\t"
    "LDR R0, [R1, R4]\n\t"

    /* Restore core registers AND the incoming task's own EXC_RETURN */
    "LDMIA R0!, {R4-R11, LR}\n\t"

    /* Was the incoming task using the FPU last time it ran? */
    "TST LR, #0x10\n\t"
    "IT EQ\n\t"
    "VLDMIAEQ R0!, {S16-S31}\n\t"

    "MSR PSP, R0\n\t"
    "BX LR\n\t"
    :
    :
    : "r0", "r1", "r2", "r3", "r4", "r5"
  );
  /* USER CODE END PendSV_IRQn 1 */
}

