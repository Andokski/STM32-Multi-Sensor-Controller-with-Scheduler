uint32_t mpu_beat = 0;

void Task_BMP280(void) {
  while (1) {
      Read_SPI_Temperature(&BMP280_Sensor);
      BMP280_Sensor.temperature_C = BMP280_Sensor.raw_temperature / 100.0f;
      
      Read_SPI_Pressure(&BMP280_Sensor);
      BMP280_Sensor.pressure_hPa = BMP280_Sensor.raw_pressure / 100.0f;
      
      bmp_beat++;
      // Brief software delay to prevent polling the sensor faster than its ODR
      LL_mDelay(10); 
  }
}

// Task 2: Dedicated exclusively to reading the MPU6050 over I2C1
void Task_MPU6050(void) {
  while (1) {
      Read_I2C_Acceleration(&MPU6050_Sensor);
      Read_I2C_Gyroscope(&MPU6050_Sensor);
      
      mpu_beat++;
      LL_mDelay(10);
  }
}
